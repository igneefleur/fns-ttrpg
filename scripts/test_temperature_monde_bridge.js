'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const betaPath = 'extension/firefox/beta/roll20-page.js';
const stablePath = 'extension/firefox/stable/roll20-page.js';
const syncPagePath = 'docs/javascripts/owd-sync.js';
const syncExtensionPath = 'extension/firefox/sync-engine.js';
const beta = fs.readFileSync(betaPath, 'utf8');
const stable = fs.readFileSync(stablePath, 'utf8');
assert.equal(beta, stable, 'les ponts beta et stable doivent rester identiques');
assert.equal(fs.readFileSync(syncPagePath, 'utf8'), fs.readFileSync(syncExtensionPath, 'utf8'),
  'le moteur de synchronisation de l’extension doit être identique à celui du site');
const debut = beta.indexOf('  function temperatureMondeDepuisAttrs(attrs) {');
const fin = beta.indexOf('\n\n  // ---------- le camp ----------', debut);
assert.ok(debut >= 0 && fin > debut, 'lecteur de température du pont introuvable');
const lire = vm.runInNewContext('(' + beta.slice(debut, fin).trim() + ')');
const attr = (v) => ({ current: typeof v === 'string' ? v : JSON.stringify(v), max: '' });
const base = (temperature) => attr({ format: 1, state: { v: 1, temperature, horloge: { jours: 1, heures: 8, minutes: 0, secondes: 0 } } });
assert.equal(lire({ owd_monde_base: base(18) }), 18);
console.log('OK température de Monde lue depuis sa photographie');
const delta = attr({ p: [['k', 'temperature']], n: ['v', -8.5] });
assert.equal(lire({ owd_monde_base: base(18), owd_monde_p_temperature: delta }), -8.5);
console.log('OK modification collaborative prioritaire sur la photographie');
const supprime = attr({ p: [['k', 'temperature']], n: ['d'] });
assert.equal(lire({ owd_monde_base: base(18), owd_monde_p_temperature: supprime }), null);
console.log('OK suppression de la température reconnue comme valeur absente');
assert.equal(lire({ owd_monde_base: base(null) }), null);
assert.equal(lire({ owd_camp_conf: attr({ v: 1, degres: 14.5 }) }), 14.5);
assert.equal(lire({ owd_camp_conf: attr({ v: 1, milieu: 'desert' }), owd_camp_h: attr('7,1430') }), 18);
assert.equal(lire({ owd_monde_base: base(1000) }), null);
console.log('OK ancienne fiche Camp, température inconnue et valeurs hors limites');
console.log('OK ponts beta/stable et moteurs de synchronisation identiques');
